    private void btn5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn5ActionPerformed
    String sql = "SELECT *FROM tb_buku";
    try{
        PreparedStatement pst = con.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();
        DefaultTableModel model = (DefaultTableModel)buku.getModel();
        model.setRowCount(0);
        while (rs.next()){
            model.addRow(new String[]{rs.getString(1),rs.getString(2),rs.getString(3),rs.getString(4),rs.getString(5)});
        }
    }   catch (SQLException ex)
        {
            System.out.println("Error   : " +ex.getMessage());
        }
    }//GEN-LAST:event_btn5ActionPerformed

    private void field6KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_field6KeyReleased
        // TODO add your handling code here:
        DefaultTableModel table = (DefaultTableModel)buku.getModel();
        String cari = field6.getText().toLowerCase();
        TableRowSorter<DefaultTableModel> tr = new TableRowSorter<DefaultTableModel>(table);
        buku.setRowSorter(tr);
        tr.setRowFilter(RowFilter.regexFilter(cari));
    }//GEN-LAST:event_field6KeyReleased

