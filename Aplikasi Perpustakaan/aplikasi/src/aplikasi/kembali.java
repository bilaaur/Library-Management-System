    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
      String abc = "SELECT * FROM tb_status";
        
        try {
            PreparedStatement pst = con.prepareStatement(abc);
            ResultSet rs = pst.executeQuery();
            DefaultTableModel model = (DefaultTableModel)tblbuku.getModel();
            model.setRowCount(0);
            while (rs.next()){
                model.addRow(new String[]{rs.getString(1),rs.getString(2),rs.getString(3),rs.getString(4),rs.getString(5),rs.getString(6),rs.getString(7),rs.getString(8),rs.getString(9),rs.getString(10)});
            }
        }catch (Exception ex){
            System.out.println("Error   : " +ex.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jTextField1KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jTextField1KeyReleased
        // TODO add your handling code here:
        DefaultTableModel table = (DefaultTableModel)tblbuku.getModel();
        String cari = jTextField1.getText().toLowerCase();
        TableRowSorter<DefaultTableModel> tr = new TableRowSorter<DefaultTableModel>(table);
        tblbuku.setRowSorter(tr);
        tr.setRowFilter(RowFilter.regexFilter(cari));
    }//GEN-LAST:event_jTextField1KeyReleased

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int row = tblbuku.getSelectedRow();
        String cell = tblbuku.getModel().getValueAt(row,0).toString();
        String sql = "delete from tb_status where ID =" +cell;
        try
        {
            PreparedStatement st =con.prepareStatement(sql);
            st.execute();
            JOptionPane.showMessageDialog(null,"Delete Berhasil!!!");
        } catch (Exception e)
        {
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

