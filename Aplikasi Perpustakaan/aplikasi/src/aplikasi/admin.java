    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {
            String query = "select * from tb_login where Username=? and Password=? and usertype=?";
            con = DriverManager.getConnection("jdbc:mysql://localhost:3306/tb_perpustakaan","root","");
            pst = con.prepareStatement(query);
            pst.setString(1,jt1.getText());
            pst.setString(2,jt2.getText());
            pst.setString(3,String.valueOf(cb1.getSelectedItem()));
            rs = pst.executeQuery();
            if (rs.next()){
                JOptionPane.showMessageDialog(this,"Anda Berhasil Login Sebagai " + rs.getString("usertype"));
            if(cb1.getSelectedIndex()==1){
                pengunjung a = new pengunjung();
                a.setVisible(true);
                this.setVisible(false);
            }else{
                buku u =new buku();
                u.setVisible(true);
                this.setVisible(false);
            }
            }else {
                JOptionPane.showMessageDialog(this, "Gagal Login");
            }
        } catch (Exception ex) {
                    JOptionPane.showMessageDialog(this, ex.getMessage());}
    }//GEN-LAST:event_jButton1ActionPerformed

